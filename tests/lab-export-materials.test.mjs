import test from 'node:test';
import assert from 'node:assert/strict';
import {browserSaveKey} from '../packages/laboratory/src/export-materials.mjs';
import {eligibleWords} from '../packages/laboratory/src/words.mjs';
import {wordPhoto} from '../packages/laboratory/src/photo.mjs';
import {experienceBridge,EXPERIENCE_KEY,levelProgress} from '../packages/laboratory/src/experience.mjs';
import {browserProgress,PROGRESS_KEY,AchievementProgress} from '../packages/laboratory/src/progress.mjs';
import {runSave,RUN_KEY} from '../packages/laboratory/src/run-save.mjs';
import {SurvivalGame} from '../packages/laboratory/src/engine.mjs';
const id='12345678-1234-4234-8234-1234567890ab';
const word={english:'garden',chinese:'花园',example:'A garden.',exampleChinese:'一座花园。',pronunciation:'/garden/',photo:'./photos/0.jpg',focus:{visible:false,box:[0,0,1,1]}};
const storage=()=>{const data=new Map();return {data,getItem:k=>data.get(k)??null,setItem:(k,v)=>data.set(k,v),removeItem:k=>data.delete(k)};};
test('selected photo, word, pronunciation and scene focus survive vocabulary filtering',()=>{
 const words=eligibleWords([word]);assert.deepEqual(words[0],{...word,photoID:undefined});
 assert.equal(wordPhoto(words[0]),'./photos/0.jpg');
 for(const photo of ['../photos/0.jpg','./photos/../secret.jpg','https://example.com/private.jpg','data:image/jpeg;base64,abc','./photos/0.jpg?x=1'])assert.equal(wordPhoto({...word,photo}),'');
});
test('new export ignores old experience, achievements and runs; own progress resumes and other exports start clean',async()=>{
 const st=storage(),scope={localStorage:st,PICLEX_LAB_EXPORT:{id,words:[word]}};
 st.setItem(EXPERIENCE_KEY,JSON.stringify(levelProgress(999)));
 const old=new AchievementProgress();old.record({}, {totalKills:100});st.setItem(PROGRESS_KEY,JSON.stringify(old.snapshot()));
 const originalGame=new SurvivalGame({words:[word]});originalGame.startWave();originalGame.coins=999;
 runSave({scope:{localStorage:st}}).save(originalGame);
 const originals=new Map(st.data);
 const xp=experienceBridge({scope});assert.equal(xp.snapshot.total,0);
 const progress=browserProgress(scope);assert.equal(progress.progress.snapshot().unlocked.length,0);
 const run=runSave({scope});assert.equal(run.snapshot,null);
 await xp.transact({id,action:'word',tier:0,cost:0,amount:1});
 progress.progress.record({}, {totalKills:1});progress.flush();
 const game=new SurvivalGame({words:[word]});game.startWave();game.coins=7;assert.equal(run.save(game),true);
 assert.equal(experienceBridge({scope}).snapshot.total,1);
 assert.equal(browserProgress(scope).progress.snapshot().counters.totalKills,1);
 assert.ok(runSave({scope}).snapshot);
 const next={...scope,PICLEX_LAB_EXPORT:{id:'22345678-1234-4234-8234-1234567890ab'}};
 assert.equal(experienceBridge({scope:next}).snapshot.total,0);
 assert.equal(browserProgress(next).progress.snapshot().unlocked.length,0);
 assert.equal(runSave({scope:next}).snapshot,null);
 for(const [k,v] of originals)assert.equal(st.getItem(k),v,'unrelated progress remains intact');
 assert.equal(browserSaveKey(RUN_KEY,{}),RUN_KEY);
});
